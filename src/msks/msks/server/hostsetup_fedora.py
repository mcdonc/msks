"""``msks-setup-fedora-host`` (#635): the Fedora deployment-host
setup — msks-setup-debian-host's phases over dnf, one
``HostProfile`` apart. The shared implementation (the capability
wrapper, the routing kernel settings, the packages, the kvm
grant, the systemd user service, the ``--uninstall`` mirror)
lives in ``hostsetup``; this module owns only the Fedora
surface:

- the package map, rpm-verified on a stock Fedora 44 install
  (Fedora Asahi, aarch64): the util-linux/libcap/procps-ng/
  iproute/nftables/kmod/e2fsprogs tools a stock Workstation
  already carries, and the conntrack-tools, qemu-img, tmux,
  virtiofsd, and libnetfilter_queue packages it ships without;
- the probe-name difference a distro makes: Debian probes
  ``update-ca-certificates``, Fedora's CA command is
  ``update-ca-trust`` (the ca-certificates package either way);
- the verbs: dnf installs with its own metadata refresh, and
  the kvm-group membership runs through usermod and gpasswd,
  shadow-utils' pair;
- the kernel-package hint an absent consent module names: the
  stock ``kernel``, or the Asahi host class's ``kernel-16k``
  (the running release carries "asahi").

Everything else — the wrapper's caps and ambient proof, the
sysctl and module files, the unit, the profile PATH block, the
VMM download — is the shared machinery reading this profile.
"""

from .hostsetup import HostProfile
from .hostsetup import main as hostsetup_main

TOOL = "msks-setup-fedora-host"

FEDORA_TOOL_PACKAGES = {
    "setpriv": "util-linux",
    "setcap": "libcap",
    "ip": "iproute",
    "nft": "nftables",
    "conntrack": "conntrack-tools",
    "modprobe": "kmod",
    "sysctl": "procps-ng",
    "mkfs.ext4": "e2fsprogs",
    "resize2fs": "e2fsprogs",
    "e2fsck": "e2fsprogs",
    "qemu-img": "qemu-img",
    "mkisofs": "genisoimage",
    "ssh": "openssh-clients",
    "rsync": "rsync",
    "tmux": "tmux",
    # Debian probes update-ca-certificates; Fedora's CA command
    # is update-ca-trust — same ca-certificates package, the
    # probe name the distro's own tool answers.
    "update-ca-trust": "ca-certificates",
    "virtiofsd": "virtiofsd",
}

FEDORA_SONAME_PACKAGES = {
    "libnetfilter_queue.so.1": "libnetfilter_queue",
    "libnfnetlink.so.0": "libnfnetlink",
}

FEDORA_PROFILE_MARKER = "# msks: Fedora keeps conntrack in /usr/sbin"

FEDORA_PROFILE_PATH_BLOCK = f"""\
{FEDORA_PROFILE_MARKER}
# added by msks-setup-fedora-host; applies at the next login
case ":$PATH:" in
  *":/usr/sbin:"*) ;;
  *) PATH="$PATH:/usr/sbin" ;;
esac
case ":$PATH:" in
  *":/sbin:"*) ;;
  *) PATH="$PATH:/sbin" ;;
esac
export PATH
"""


def fedora_kernel_package(machine: str, release: str) -> str:
    """The stock kernel's package for this host: the Asahi host
    class runs the 16K flavour (its release string carries
    "asahi"), every other Fedora machine the unsuffixed kernel."""
    return "kernel-16k" if "asahi" in release else "kernel"


FEDORA_PROFILE = HostProfile(
    tool=TOOL,
    label="Fedora",
    os_id="fedora",
    description=(
        "Prepare a Fedora deployment host for msksd "
        "(#635): the capability wrapper, the routing kernel "
        "settings, and a systemd service for the daemon (#560)."
    ),
    tool_packages=FEDORA_TOOL_PACKAGES,
    soname_packages=FEDORA_SONAME_PACKAGES,
    refresh_command=None,
    install_command=("dnf", "install", "-y"),
    install_timeout=600.0,
    package_manager="dnf",
    remove_command=("dnf", "remove"),
    install_env={},
    admin_path="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
    modules_header=(
        "# msksd egress prerequisites (msks-setup-fedora-host): "
        "taps, the\n# nftables machinery, NAT, conntrack, the deny "
        "RST, and the\n# interactive consent queue.\n"
    ),
    profile_marker=FEDORA_PROFILE_MARKER,
    profile_path_block=FEDORA_PROFILE_PATH_BLOCK,
    unit_header=(
        "# Generated by msks-setup-fedora-host (#635): re-run "
        "the tool to refresh this file."
    ),
    kernel_package=fedora_kernel_package,
    group_add=lambda user, group: ["usermod", "-a", "-G", group, user],
    group_remove=lambda user, group: ["gpasswd", "-d", user, group],
    group_restore=lambda user: f"usermod -aG kvm {user}",
)


def main(argv: list[str] | None = None) -> int:
    """The console entry: 0 on success, 1 on a named refusal."""
    return hostsetup_main(argv, profile=FEDORA_PROFILE)
