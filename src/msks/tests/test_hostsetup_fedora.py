"""msks-setup-fedora-host (#635): the Fedora profile over the
shared hostsetup machinery. The rig is the Debian suite's own
(test_hostsetup.Host); the fixture swaps the os-release, the
entry, and the two group commands the Fedora profile execs."""

from pathlib import Path

import msks.server.hostsetup as hostsetup
import pytest
from msks.server.hostsetup import CAPS, WRAPPER
from msks.server.hostsetup_fedora import FEDORA_PROFILE, main
from test_hostsetup import Host


class FedoraHost(Host):
    """The fake Fedora host: usermod and gpasswd answer where the
    Debian rig taught adduser and deluser."""

    def __init__(self) -> None:
        super().__init__()
        self.usermod_rc = 0
        self.gpasswd_rc = 0

    def sh(self, cmd, timeout=10.0, env=None):
        head = cmd[0]
        if head == "usermod":
            if self.usermod_rc != 0:
                return self.usermod_rc, "", "usermod: refused\n"
        if head == "gpasswd":
            if self.gpasswd_rc != 0:
                return self.gpasswd_rc, "", "gpasswd: refused\n"
        return super().sh(cmd, timeout=timeout, env=env)


@pytest.fixture()
def fedora_host(monkeypatch: pytest.MonkeyPatch, tmp_path: Path):
    host = FedoraHost()
    release = tmp_path / "os-release"
    release.write_text('ID="fedora"\n')
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    (bin_dir / "msksd").write_text("#!/bin/sh\n")
    monkeypatch.setattr(
        hostsetup.sys, "argv", [str(bin_dir / "msks-setup-fedora-host")]
    )
    manager = tmp_path / "systemd"
    manager.mkdir()
    monkeypatch.setattr(hostsetup, "SYSTEMD_MANAGER", str(manager))
    monkeypatch.setattr(hostsetup, "group_present", lambda name: name == "kvm")
    monkeypatch.setattr(hostsetup, "in_group", lambda user, name: False)
    home = tmp_path / "home" / "chrism"
    home.mkdir(parents=True)
    monkeypatch.setattr(
        hostsetup, "executing_user", lambda: ("chrism", 1000, 1000, str(home))
    )
    runtime = tmp_path / "run-user-1000"
    runtime.mkdir()
    monkeypatch.setattr(
        hostsetup, "RUNTIME_DIR_FMT", str(runtime.parent / "run-user-{}")
    )
    monkeypatch.setattr(
        hostsetup,
        "chown_path",
        lambda path, uid, gid: None,
    )
    monkeypatch.setattr(hostsetup, "RETRY_DELAY", 0.0)
    monkeypatch.setattr(hostsetup, "sh", host.sh)
    monkeypatch.setattr(hostsetup, "write_file", host.write)
    monkeypatch.setattr(hostsetup, "read_file", host.read)
    monkeypatch.setattr(hostsetup, "file_exists", lambda p: p in host.files)
    monkeypatch.setattr(hostsetup, "remove_file", host.remove_file)
    monkeypatch.setattr(hostsetup, "replace_file", lambda source, target: None)
    monkeypatch.setattr(
        hostsetup, "CLOUD_HYPERVISOR_BIN", str(tmp_path / "cloud-hypervisor")
    )
    monkeypatch.setattr(hostsetup, "OS_RELEASE", str(release))
    monkeypatch.setattr(hostsetup.os, "geteuid", lambda: 0)
    monkeypatch.setattr(hostsetup, "which", lambda tool: f"/usr/bin/{tool}")
    yield host


def test_non_root_refuses_before_anything(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture
) -> None:
    monkeypatch.setattr(hostsetup.os, "geteuid", lambda: 1000)
    monkeypatch.setattr(
        hostsetup.sys,
        "argv",
        ["/opt/msks/bin/msks-setup-fedora-host"],
    )
    assert main() == 1
    assert "run me as root (sudo /opt/msks/bin/msks-setup-fedora-host)" in (
        capsys.readouterr().err
    )


def test_non_fedora_host_refuses_by_name(
    fedora_host: FedoraHost, capsys: pytest.CaptureFixture
) -> None:
    Path(hostsetup.OS_RELEASE).write_text("ID=debian\n")
    assert main() == 1
    assert "targets Fedora hosts (os-release says 'debian')" in (
        capsys.readouterr().err
    )
    assert fedora_host.commands == []


def test_happy_path_lands_every_piece(
    fedora_host: FedoraHost, tmp_path: Path, capsys: pytest.CaptureFixture
) -> None:
    assert main() == 0
    # Every tool answered present: dnf never ran.
    assert fedora_host.ran("dnf") == []
    # The wrapper: the same setpriv copy, caps, proof as Debian.
    assert fedora_host.ran("setcap") == [["setcap", f"{CAPS}+ep", WRAPPER]]
    assert fedora_host.ran("usermod") == [
        ["usermod", "-a", "-G", "kvm", "chrism"]
    ]
    # The landed files name the Fedora tool.
    assert fedora_host.writes[hostsetup.MODULES_FILE].startswith(
        "# msksd egress prerequisites (msks-setup-fedora-host):"
    )
    home = tmp_path / "home" / "chrism"
    unit = fedora_host.writes[hostsetup.unit_path(str(home))]
    assert unit.startswith(
        "# Generated by msks-setup-fedora-host (#635): re-run"
    )
    # The rig's replace_file is a no-op, so the profile write
    # lands at the atomic-partial path the real rename would move.
    profile_block = fedora_host.writes[str(home / ".profile.msks-new")]
    assert FEDORA_PROFILE.profile_marker in profile_block
    out = capsys.readouterr().out
    assert "msks-setup-fedora-host: done —" in out
    assert "consent:    interactive egress consent available" in out
    assert "dev-daemon use: DEV_CAPS=/usr/local/bin/msks-caps msks-dev" in out


def test_missing_tools_install_via_dnf(
    fedora_host: FedoraHost, monkeypatch: pytest.MonkeyPatch
) -> None:
    real_which = hostsetup.which

    def lacking(tool):
        return None if tool == "conntrack" else real_which(tool)

    monkeypatch.setattr(hostsetup, "which", lacking)
    assert main() == 0
    # dnf refreshes metadata as part of install: one command.
    assert fedora_host.ran("dnf") == [
        ["dnf", "install", "-y", "conntrack-tools"]
    ]


def test_the_ca_probe_names_fedora_command(
    fedora_host: FedoraHost, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Debian probes update-ca-certificates; the Fedora map
    probes update-ca-trust — the absence lands the same
    ca-certificates package."""
    real_which = hostsetup.which

    def lacking(tool):
        return None if tool == "update-ca-trust" else real_which(tool)

    monkeypatch.setattr(hostsetup, "which", lacking)
    assert "update-ca-certificates" not in FEDORA_PROFILE.tool_packages
    assert main() == 0
    assert fedora_host.ran("dnf") == [
        ["dnf", "install", "-y", "ca-certificates"]
    ]


