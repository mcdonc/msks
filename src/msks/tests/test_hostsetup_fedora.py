def test_uninstall_round_trips_every_piece(
    fedora_host: FedoraHost,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture,
) -> None:
    assert main() == 0
    # The install's `install` command landed the wrapper — the
    # rig records commands, not their effects, so the file the
    # uninstall's probe reads is seeded here.
    fedora_host.files.add(WRAPPER)
    # The install's usermod landed the membership; the uninstall
    # reads it back before removing it.
    monkeypatch.setattr(hostsetup, "in_group", lambda user, name: True)
    assert main(["--uninstall"]) == 0
    host = fedora_host
    assert host.ran("gpasswd") == [["gpasswd", "-d", "chrism", "kvm"]]
    out = capsys.readouterr().out
    assert "msks-setup-fedora-host: done —" in out
    assert "dnf remove " in out
    assert "conntrack-tools" in out
    # Every landed file left: the wrapper, both kernel files, the
    # unit, its wants symlink, and the profile block's file.
    home = tmp_path / "home" / "chrism"
    for path in (
        WRAPPER,
        hostsetup.SYSCTL_FILE,
        hostsetup.MODULES_FILE,
        hostsetup.unit_path(str(home)),
    ):
        assert path in host.removals
